import numpy as np
import networkx as nx
import matplotlib.pyplot as plt

# ==========================================
# 1. Ввод графа с помощью матрицы смежности
# ==========================================
# Матрица из задания:
# ( 1 1 1 )
# ( 1 1 1 )
# ( 1 0 1 )

A = np.array([
    [1, 1, 1],
    [1, 1, 1],
    [1, 0, 1]
], dtype=int)

print("1. Исходная матрица смежности (A):")
print(A)
print("-" * 30)

# ==========================================
# 2. Вывод рисунка графа
# ==========================================
print("2. Построение рисунка графа...")

# Создаем граф (неориентированный, так как матрица симметрична)
G = nx.Graph()

# Добавляем узлы (0, 1, 2)
G.add_nodes_from(range(3))

# Добавляем ребра на основе матрицы смежности
# Так как матрица симметрична, проходим по верхнему треугольнику, чтобы не дублировать ребра
rows, cols = np.where(np.triu(A) == 1)
for u, v in zip(rows, cols):
    G.add_edge(u, v)

# Задаем позиции узлов (треугольником)
pos = {
    0: (0, 1),    # Верхний узел
    1: (-1, -1),  # Левый нижний
    2: (1, -1)    # Правый нижний
}

plt.figure(figsize=(6, 5))
# Рисуем узлы
nx.draw_networkx_nodes(G, pos, node_size=700, node_color='lightgreen')
# Рисуем подписи узлов
nx.draw_networkx_labels(G, pos, font_size=14, font_weight='bold')
# Рисуем ребра
nx.draw_networkx_edges(G, pos, width=1.5, edge_color='gray')

plt.title("Визуализация графа (Задание 3)")
plt.axis('off')
plt.show()

print("-" * 30)

# ==========================================
# 3. Спектр графа (Собственные значения)
# ==========================================
print("3. Спектр графа (Собственные значения):")

# Используем np.linalg.eig для поиска собственных значений и векторов
# (для симметричной матрицы можно использовать eigvalsh, но eig более универсален)
eigenvalues, eigenvectors = np.linalg.eig(A)

# Сортируем собственные значения по убыванию для удобства
idx = eigenvalues.argsort()[::-1]
eigenvalues = eigenvalues[idx]
eigenvectors = eigenvectors[:, idx]

for i, val in enumerate(eigenvalues):
    # Если мнимая часть очень мала, считаем число действительным
    if np.isclose(val.imag, 0):
        print(f"λ_{i+1} = {np.round(val.real, 4)}")
    else:
        print(f"λ_{i+1} = {np.round(val.real, 4)} + {np.round(val.imag, 4)}i")

print("-" * 30)

# ==========================================
# 4. Вывод уравнения для тетради
# ==========================================
print("4. Характеристическое уравнение для записи в тетрадь:")
# Найдем коэффициенты полинома
coeffs = np.poly(A)
# coeffs: [1, -c2, c1, -c0] для lambda^3 + ...
# Формируем строку уравнения
eq_str = f"λ^3 + ({coeffs[1]:.1f})λ^2 + ({coeffs[2]:.1f})λ + ({coeffs[3]:.1f}) = 0"
print(eq_str)
print("-" * 30)

# ==========================================
# 5. НАХОЖДЕНИЕ СПЕКТРА МАТРИЦЫ (ДОБАВЛЕНО)
# ==========================================
print("5. Нахождение спектра матрицы (детальный вывод):")
print("Спектр матрицы — это множество всех её собственных значений.")
print("Для матрицы A спектр состоит из следующих чисел:")

# Вывод в виде множества
spectrum = set()
for val in eigenvalues:
    if np.isclose(val.imag, 0):
        spectrum.add(np.round(val.real, 4))
    else:
        spectrum.add(complex(np.round(val.real, 4), np.round(val.imag, 4)))

print(f"Спектр = {spectrum}")
print()

# Вывод собственных векторов (для справки)
print("Собственные векторы (для проверки):")
for i in range(len(eigenvalues)):
    vec = eigenvectors[:, i]
    print(f"Для λ_{i+1} = {np.round(eigenvalues[i].real, 4)}:")
    print(f"  Вектор: {np.round(vec.real, 4)}")
print("-" * 30)

# ==========================================
# Пояснение для тетради
# ==========================================
print("Пояснение для записи в тетрадь:")
print("1. Матрица смежности A имеет вид:")
print(A)
print("2. Характеристическое уравнение: det(A - λI) = 0")
print("3. Раскрывая определитель, получаем уравнение:")
print("   λ^3 - 3λ^2 + λ = 0  =>  λ(λ^2 - 3λ + 1) = 0")
print("4. Корни уравнения (спектр):")
print("   λ1 = 0")
print("   λ2 = (3 + √5) / 2 ≈ 2.618")
print("   λ3 = (3 - √5) / 2 ≈ 0.382")
print("   (Проверка: сумма корней 0 + 2.618 + 0.382 = 3, след матрицы 1+1+1 = 3. Верно!)")