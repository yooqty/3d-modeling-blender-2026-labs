def main():
    # Организуем ввод количества вершин
    while True:
        try:
            n = int(input("Введите количество вершин: "))
            if n > 0:
                break
            else:
                print("Количество вершин должно быть больше 0.")
        except ValueError:
            print("Ошибка: введите целое число.")

    # Вычисляем количество ребер для полного графа
    # Формула: n * (n - 1) / 2
    full_graph_edges = n * (n - 1) // 2

    # Вычисляем количество ребер для дерева
    # Формула: n - 1
    tree_edges = n - 1

    # Выводим результаты
    print(f"\nДля графа с {n} вершинами:")
    print(f"Количество ребер в полном графе: {full_graph_edges}")
    print(f"Количество ребер в дереве: {tree_edges}")

if __name__ == "__main__":
    main()