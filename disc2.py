import networkx as nx
import matplotlib.pyplot as plt

# --- 1. СОЗДАНИЕ ГРАФА (ЛЕВЫЙ) ---
G1 = nx.Graph()

# Добавляем ребра (связи), как на левой картинке
edges1 = [
    (0, 5), (0, 4), (0, 7), 
    (5, 4), (5, 1), (5, 7),
    (4, 8), (4, 1), (4, 2), (4, 9),
    (8, 6), (8, 2),
    (6, 1), (6, 9), (6, 2),
    (1, 9),
    (7, 9), (7, 2),
    (2, 9),
    (3, 6), (3, 9)
]
G1.add_edges_from(edges1)

# Задаем координаты для левого графа (приблизительно по картинке)
pos1 = {
    0: (0, 10),
    5: (0, 7),
    7: (0.5, 1),
    4: (2, 8.5),
    8: (3, 9.8),
    1: (2, 6),
    6: (4, 7.5),
    9: (2.5, 4),
    3: (4, 4.5),
    2: (2, 1)
}

# --- 2. СОЗДАНИЕ ГРАФА (ПРАВЫЙ) ---
G2 = nx.Graph()

# Добавляем ребра (связи), как на правой картинке
edges2 = [
    (4, 5), (4, 3), (4, 0),
    (3, 9), (3, 2), (3, 4),
    (2, 8), (2, 9), (2, 1), (2, 3),
    (1, 7), (1, 8), (1, 2),
    (0, 6), (0, 7), (0, 4),
    (6, 5), (6, 7), (6, 8), (6, 9), (6, 0),
    (5, 7), (5, 8), (5, 9), (5, 6), (5, 4),
    (7, 8), (7, 9),
    (8, 9)
]
G2.add_edges_from(edges2)

# Задаем координаты для правого графа
pos2 = {
    4: (2, 10),
    0: (0, 6),
    3: (4, 9),
    5: (2.5, 8.5),
    9: (3.5, 7.5),
    6: (1.5, 7),
    7: (1.5, 2.5),
    8: (2.5, 3.5),
    2: (4, 3),
    1: (2, 0.5)
}

# --- 3. ОТРИСОВКА ---
plt.figure(figsize=(14, 7))

# Рисуем первый граф
plt.subplot(121)
nx.draw(G1, pos1, with_labels=True, node_size=600, node_color='#1f78b4', 
        font_color='white', font_weight='bold', edge_color='gray', width=1.5)
plt.title("Граф 1 (Левый)")

# Рисуем второй граф
plt.subplot(122)
nx.draw(G2, pos2, with_labels=True, node_size=600, node_color='#1f78b4', 
        font_color='white', font_weight='bold', edge_color='gray', width=1.5)
plt.title("Граф 2 (Правый)")

plt.show()