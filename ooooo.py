import numpy as np
import networkx as nx
import matplotlib.pyplot as plt

# ==========================================
# 1. Ввод графа с помощью матрицы смежности
# ==========================================
# Матрица смежности из задания (3 вершины)
# По умолчанию вершины: 0, 1, 2. Назовем их A, B, C (или V1, V2, V3)
# Но в задании есть упоминание "B" и "D". 
# Если вершин 3, то скорее всего это вершины 1, 2, 3 (или A, B, C).
# Предположим, что матрица задает граф с вершинами V1, V2, V3.

adj_matrix = np.array([
    [0, 1, 1],
    [1, 0, 1],
    [1, 0, 1]
])

n = adj_matrix.shape[0]
nodes = [f"V{i+1}" for i in range(n)] # V1, V2, V3

print("--- 1. Матрица смежности ---")
print(adj_matrix)
print(f"Вершины: {nodes}\n")

# ==========================================
# 2. Создание ориентированного графа
# ==========================================
# Условие: "Сделать граф ориентированным по часовой стрелке, направление от B к D"
# В матрице 3x3 вершины обычно нумеруются 1, 2, 3.
# Если следовать логике задачи 2, где были A, B, C, D, то здесь, возможно, 
# подразумеваются вершины A, B, C (или 1, 2, 3).
# "Направление от B к D" — если вершин 3, то D может быть опечаткой или 
# имеется в виду 3-я вершина (V3).
# 
# Давайте интерпретировать это так:
# V1 = A, V2 = B, V3 = D (или C, но пусть будет D для соответствия условию).
# Ориентация по часовой стрелке: V1 -> V2 -> V3 -> V1
# Направление от B к D: V2 -> V3

# Создаем ориентированный граф
DG = nx.DiGraph()

# Добавляем вершины
DG.add_nodes_from(nodes)

# Добавляем ребра согласно матрице смежности и условию ориентации
# Матрица показывает, что есть ребра: (V1,V2), (V1,V3), (V2,V1), (V2,V3), (V3,V1), (V3,V2)? 
# Нет, матрица:
# [0 1 1] -> V1 связана с V2 и V3
# [1 0 1] -> V2 связана с V1 и V3
# [1 0 1] -> V3 связана с V1 и V3? (Нет, V3 связана с V1, но не с V2, так как 0)
# Итак, ребра: V1-V2, V1-V3, V2-V3.

# Ориентируем по часовой стрелке: V1 -> V2 -> V3 -> V1
# И добавляем направление от B (V2) к D (V3), что уже есть в цепочке V2 -> V3.

edges_dir = [
    ('V1', 'V2'), # A -> B
    ('V2', 'V3'), # B -> D (по условию)
    ('V3', 'V1')  # D -> A (замыкаем круг по часовой)
]

# Проверка: в матрице смежности есть ребро V2-V1, но мы делаем V1->V2. 
# Это нормально для ориентированного графа, мы выбираем направление.
# Также в матрице есть V3-V2, но мы делаем V2->V3. 

DG.add_edges_from(edges_dir)

print("--- 2. Ориентированный граф (по часовой стрелке) ---")
print("Ребра:")
for u, v in DG.edges():
    print(f"{u} -> {v}")
print()

# ==========================================
# 3. Матрица смежности ориентированного графа
# ==========================================
# Создаем матрицу смежности для ориентированного графа
# Строка - откуда, Столбец - куда
adj_matrix_dir = np.zeros((n, n), dtype=int)

for u, v in DG.edges():
    u_idx = nodes.index(u)
    v_idx = nodes.index(v)
    adj_matrix_dir[u_idx][v_idx] = 1

print("--- 3. Матрица смежности ориентированного графа ---")
print(adj_matrix_dir)
print()

# ==========================================
# 4. Спектр графа (Собственные значения)
# ==========================================
# Для ориентированного графа спектр обычно ищут для матрицы смежности 
# (или для матрицы Лапласа, если граф симметричен).
# Так как граф ориентированный, используем матрицу смежности.

eigenvalues = np.linalg.eigvals(adj_matrix_dir)

print("--- 4. Спектр графа (Собственные значения матрицы смежности) ---")
print("Собственные значения (комплексные числа):")
for val in eigenvalues:
    print(f"{val:.4f}")
print()

# ==========================================
# 5. Характеристическое уравнение (для тетради)
# ==========================================
# Для матрицы 3x3 уравнение имеет вид: λ^3 - c1*λ^2 + c2*λ - c3 = 0
# Коэффициенты можно найти через np.poly

coeffs = np.poly(adj_matrix_dir)
print("--- 5. Характеристическое уравнение (коэффициенты) ---")
print(f"{coeffs[0]:.0f}*λ^3 + {coeffs[1]:.0f}*λ^2 + {coeffs[2]:.0f}*λ + {coeffs[3]:.0f} = 0")
print()

# ==========================================
# 6. Визуализация графа
# ==========================================
plt.figure(figsize=(6, 6))
pos = {'V1': (1, 0), 'V2': (0, 1), 'V3': (-1, -1)} # Примерное расположение

nx.draw(DG, pos, with_labels=True, node_color='lightcoral', 
        node_size=1000, font_weight='bold', font_size=14, 
        arrows=True, arrowsize=25, edge_color='gray', width=2)

plt.title("Ориентированный граф (по часовой стрелке)")
plt.axis('off')
plt.show()