def main():
    # Организуем ввод количества вершин
    while True:
        try:
            n = int(input("Введите количество вершин (n): "))
            if n > 0:
                break
            else:
                print("Ошибка: количество вершин должно быть больше 0.")
        except ValueError:
            print("Ошибка: введите целое число.")

    # 1. Пустой граф (Empty graph)
    # Все вершины изолированы, нет ребер. Достаточно 1 цвета.
    # Если n = 0, то 0 цветов, но мы условились, что n > 0.
    chi_empty = 1

    # 2. Полный граф (Complete graph)
    # Каждая вершина соединена с каждой. Нужно n цветов.
    chi_complete = n

    # 3. Дерево (Tree)
    # Дерево всегда двудольно (2 цвета), если n > 1.
    # Если n = 1 (одна вершина без ребер), то 1 цвет.
    if n == 1:
        chi_tree = 1
    else:
        chi_tree = 2

    # 4. Простой цикл Cn (Simple cycle)
    # Если n четное -> 2 цвета.
    # Если n нечетное -> 3 цвета.
    # Исключение: n = 1 (петля, но обычно цикл начинается с n >= 3).
    # Для n=1 или n=2 это не цикл в классическом понимании, но формально:
    if n % 2 == 0:
        chi_cycle = 2
    else:
        # Для нечетных n >= 3
        chi_cycle = 3
        # Если n = 1, это петля (обычно не рассматривается как простой цикл)
        if n == 1:
            chi_cycle = 1  # Петля требует 1 цвет, если это просто вершина

    # Вывод результатов
    print(f"\nДля n = {n}:")
    print(f"Хроматическое число пустого графа: {chi_empty}")
    print(f"Хроматическое число полного графа: {chi_complete}")
    print(f"Хроматическое число дерева: {chi_tree}")
    print(f"Хроматическое число простого цикла C{n}: {chi_cycle}")

if __name__ == "__main__":
    main()