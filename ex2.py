import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
import sympy as sp

# ============================================================
# 1. Ввод матрицы смежности (из задания)
# ============================================================
# Матрица 3x3:
# [1 1 0]
# [0 1 1]
# [1 0 0]
# ВАЖНО: В задании матрица несимметричная (ориентированный граф), 
# но для матрицы Кирхгофа и спектральной кластеризации обычно 
# используют неориентированные графы. 
# Сделаем матрицу симметричной (если A[i][j]=1, то и A[j][i]=1),
# чтобы можно было корректно построить матрицу Кирхгофа.
A_raw = np.array([
    [1, 1, 0],
    [0, 1, 1],
    [1, 0, 0]
])

# Делаем граф неориентированным (симметричная матрица)
A = np.maximum(A_raw, A_raw.T)

# Убираем петли (на диагонали стоят 1, что означает петлю у вершины, 
# обычно в таких задачах петли не учитывают, занулим диагональ)
np.fill_diagonal(A, 0)

print("="*60)
print("1. ИСХОДНАЯ МАТРИЦА СМЕЖНОСТИ (из задания):")
print("="*60)
print(A_raw)
print("\nМатрица смежности, используемая для расчетов (неориентированная, без петель):")
print(A)

# ============================================================
# 2. Вывод рисунка графа
# ============================================================
G = nx.from_numpy_array(A)
pos = {0: (0, 1), 1: (1, 1), 2: (0.5, 0)} # Треугольник

plt.figure(figsize=(5, 5))
nx.draw(G, pos, with_labels=[1, 2, 3], node_color='red',
        node_size=700, font_color='white', font_weight='bold', edge_color='gray', width=2)
plt.title("Рисунок графа")
plt.show()

# ============================================================
# 3. Матрица Кирхгофа и уравнение для расчета собственных значений
# ============================================================
degrees = np.sum(A, axis=1)
D = np.diag(degrees)
L = D - A

print("\n" + "="*60)
print("2. УРАВНЕНИЕ ДЛЯ РАСЧЕТА СОБСТВЕННЫХ ЗНАЧЕНИЙ (по матрице Кирхгофа):")
print("="*60)
print("Матрица Кирхгофа L = D - A:")
print(L)

lam = sp.symbols('lambda')
L_sym = sp.Matrix(L)
I = sp.eye(3)
char_matrix = L_sym - lam * I

print("\nХарактеристическая матрица (L - λI):")
sp.pprint(char_matrix)
print("\nУравнение det(L - λI) = 0:")
sp.pprint(sp.Eq(char_matrix.det(), 0))

# ============================================================
# 4. Собственные значения и вектор Фидлера
# ============================================================
eigenvalues, eigenvectors = np.linalg.eigh(L)

print("\n" + "="*60)
print("3. СОБСТВЕННЫЕ ЗНАЧЕНИЯ И ВЕКТОР ФИДЛЕРА:")
print("="*60)
print("Собственные значения (отсортированы по возрастанию):")
for i, val in enumerate(eigenvalues):
    print(f"  λ{i+1} = {val:.4f}")

# Вектор Фидлера (индекс 1 - второй по величине)
fiedler_vector = eigenvectors[:, 1]

print("\nВектор Фидлера (соответствует λ2):")
print(np.round(fiedler_vector, 4))

# Для удобства записываем нормализованный вектор в тетрадь (целые числа)
non_zero_vals = np.abs(fiedler_vector[np.abs(fiedler_vector) > 1e-5])
min_val = np.min(non_zero_vals)
fiedler_norm = fiedler_vector / min_val
if fiedler_norm[0] < 0:
    fiedler_norm = -fiedler_norm

print("\nВектор Фидлера (нормализованный для тетради):")
print(np.round(fiedler_norm, 4))