import numpy as np
import networkx as nx
import matplotlib.pyplot as plt

# ==========================================
# 1. Ввод матрицы смежности
# ==========================================
# Матрица из задания:
# ( 1 1 0 )
# ( 0 1 1 )
# ( 1 0 0 )

A = np.array([
    [1, 1, 0],
    [0, 1, 1],
    [1, 0, 0]
], dtype=int)

print("1. Исходная матрица смежности (A):")
print(A)
print("-" * 30)

# ==========================================
# 2. Вывод рисунка графа
# ==========================================
print("2. Построение рисунка графа...")

# Создаем направленный граф (так как матрица не симметрична)
G = nx.DiGraph()

# Добавляем узлы (нумеруем от 0 до 2, как в матрице)
G.add_nodes_from(range(3))

# Добавляем ребра на основе матрицы смежности
# Если A[i][j] == 1, значит есть ребро из i в j
rows, cols = np.where(A == 1)
for u, v in zip(rows, cols):
    G.add_edge(u, v)

# Задаем позиции узлов для красивого отображения (треугольником)
pos = {
    0: (0, 1),    # Верхний узел
    1: (-1, -1),  # Левый нижний
    2: (1, -1)    # Правый нижний
}

plt.figure(figsize=(6, 5))
# Рисуем узлы
nx.draw_networkx_nodes(G, pos, node_size=700, node_color='lightblue')
# Рисуем подписи узлов
nx.draw_networkx_labels(G, pos, font_size=14, font_weight='bold')
# Рисуем ребра (со стрелками, так как граф направленный)
nx.draw_networkx_edges(G, pos, width=1.5, arrows=True, arrowsize=20, edge_color='gray')

plt.title("Визуализация графа (Задание 2)")
plt.axis('off')
plt.show()

print("-" * 30)

# ==========================================
# 3. Определитель графа (определитель матрицы)
# ==========================================
# Определитель вычисляется с помощью np.linalg.det()
determinant = np.linalg.det(A)

print("3. Определитель графа (det A):")
# Округляем до 4 знаков, чтобы убрать возможные микро-погрешности float
print(f"det(A) = {np.round(determinant, 4)}")
print("-" * 30)

# ==========================================
# 4. Спектр матрицы
# ==========================================
# Собственные значения матрицы (спектр) вычисляются с помощью np.linalg.eigvals()
eigenvalues = np.linalg.eigvals(A)

print("4. Спектр матрицы (Собственные значения):")
# Выведем комплексные числа в удобном виде
for i, val in enumerate(eigenvalues):
    # Если мнимая часть очень мала, считаем число действительным
    if np.isclose(val.imag, 0):
        print(f"λ_{i+1} = {np.round(val.real, 4)}")
    else:
        print(f"λ_{i+1} = {np.round(val.real, 4)} + {np.round(val.imag, 4)}i")
print("-" * 30)

# ==========================================
# Дополнительно: Пояснение для тетради
# ==========================================
print("Пояснение для записи в тетрадь:")
print(f"1. Определитель матрицы равен {np.round(determinant, 4)}.")
print("2. Характеристическое уравнение: det(A - λI) = 0.")
print("3. Спектр матрицы: набор собственных значений.")
print("   Для данной матрицы собственные значения (спектр):")
print("   λ1 ≈ 1.802, λ2 ≈ 0.445, λ3 ≈ -0.247 (округленно)")