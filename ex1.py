import numpy as np
import networkx as nx
import matplotlib.pyplot as plt

# --- 1. Ввод графа с помощью матрицы смежности ---
# Узлы пронумеруем от 0 до 3 (или 1 до 4, но в программировании обычно с 0)
# Соседи: 0-1, 0-2, 1-3, 2-3, 1-2 (соединены горизонтально)
# Матрица смежности A
#   0 1 2 3
A = np.array([
    [0, 1, 1, 0], # Узел 0 связан с 1 и 2
    [1, 0, 1, 1], # Узел 1 связан с 0, 2 и 3
    [1, 1, 0, 1], # Узел 2 связан с 0, 1 и 3
    [0, 1, 1, 0]  # Узел 3 связан с 1 и 2
])

print("1. Матрица смежности (A):")
print(A)
print("-" * 30)

# --- 2. Матрица инцидентности ---
# Обозначим ребра:
# e1: 0-1
# e2: 0-2
# e3: 1-2
# e4: 1-3
# e5: 2-3
# Размер матрицы: узлы x ребра (4x5)
# 1 - ребро выходит из узла, -1 - входит (для неориентированного графа выбираем направление условно)
# Или просто 1, если узел является концом ребра (обычно используется 1 и -1, либо 1 и 1)
# Используем стандартный вид: 1 и -1 для ориентированного представления, или 1 для обоих концов.
# Для матрицы Кирхгофа обычно строят матрицу инцидентности B (размер V x E), где B[i][e] = 1, если e инцидентно i.
# Но часто для расчета Лапласиана используют B*B^T.

# Создадим матрицу инцидентности (4 узла, 5 ребер)
# Предположим ориентацию: от меньшего индекса к большему
Inc = np.zeros((4, 5), dtype=int)
edges = [(0, 1), (0, 2), (1, 2), (1, 3), (2, 3)]

for i, (u, v) in enumerate(edges):
    Inc[u, i] = 1
    Inc[v, i] = -1 # Для ориентированного графа. Если нужен неориентированный, поставьте 1.

print("2. Матрица инцидентности (Inc):")
print(Inc)
print("   (Столбцы соответствуют ребрам: e1, e2, e3, e4, e5)")
print("-" * 30)

# --- 3. Матрица Кирхгофа и Лапласа ---
# Матрица степеней D
D = np.diag(np.sum(A, axis=1))

# Матрица Лапласа L = D - A
L = D - A

print("3. Матрица Кирхгофа (Лапласа) L:")
print(L)
print("-" * 30)

# --- 4. Спектр графа ---
# Собственные значения матрицы Лапласа
eigenvalues = np.linalg.eigvalsh(L) # eigvalsh для симметричных матриц
# Округлим для красоты
eigenvalues = np.round(eigenvalues, 4)

print("4. Спектр графа (Собственные значения):")
print(eigenvalues)
print("-" * 30)

# --- 5. Вывод уравнения (Характеристическое уравнение) ---
# Уравнение: det(L - lambda * I) = 0
print("Характеристическое уравнение (det(L - λI) = 0):")
# Для вывода уравнения в общем виде используем sympy (если установлен), 
# либо просто распишем коэффициенты.
# Попробуем воссоздать формулу вручную для этого графа.
# Характеристический многочлен для данного графа: λ(λ-2)(λ-4)(λ-4) = 0 ? Проверим.
# Найдем коэффициенты полинома
coeffs = np.poly(L)
# coeffs: [1, -c3, c2, -c1, c0] для lambda^4 + ...
print(f"Полином: λ^4 + ({coeffs[1]:.1f})λ^3 + ({coeffs[2]:.1f})λ^2 + ({coeffs[3]:.1f})λ + ({coeffs[4]:.1f}) = 0")
print("Или в виде: λ(λ - 2)(λ - 4)^2 = 0")
print("-" * 30)

print("Пояснение для тетради:")
print("Спектр состоит из собственных значений: 0, 2, 4, 4.")
print("Уравнение: λ^4 - 10λ^3 + 32λ^2 - 32λ = 0")
print("-" * 30)


# ==========================================
# БЛОК ВИЗУАЛИЗАЦИИ ГРАФА
# ==========================================
print("Построение изображения графа...")

# Создаем объект графа
G = nx.Graph()

# Добавляем узлы (от 0 до 3)
G.add_nodes_from(range(4))

# Добавляем ребра на основе матрицы смежности A
# (проходим по верхнему треугольнику матрицы, чтобы не дублировать ребра)
rows, cols = np.where(np.triu(A) == 1)
for u, v in zip(rows, cols):
    G.add_edge(u, v)

# Задаем позиции узлов вручную, чтобы получился ромб, как на картинке
# Узел 0 - сверху, 1 - слева, 2 - справа, 3 - снизу
pos = {
    0: (0, 1),    # Верх
    1: (-1, 0),   # Лево
    2: (1, 0),    # Право
    3: (0, -1)    # Низ
}

# Рисуем
plt.figure(figsize=(6, 6))
nx.draw_networkx_nodes(G, pos, node_size=800, node_color='red')
nx.draw_networkx_labels(G, pos, font_color='white', font_weight='bold')
nx.draw_networkx_edges(G, pos, width=2, edge_color='gray')

plt.title("Визуализация графа из задания")
plt.axis('off') # Отключаем оси координат
plt.show()