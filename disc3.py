def check_graphical_sequence(degrees):
    # Причина 1: Проверка на отрицательные числа
    if any(d < 0 for d in degrees):
        return False, "Степени вершин не могут быть отрицательными."

    n = len(degrees)
    
    # Причина 2: Проверка на четность суммы (Лемма о рукопожатиях)
    if sum(degrees) % 2 != 0:
        return False, "Сумма степеней всех вершин должна быть четной (Лемма о рукопожатиях)."

    # Причина 3: Проверка на максимальную степень
    # В простом графе максимальная степень вершины не может быть больше n-1
    if any(d >= n for d in degrees):
        return False, f"Степень вершины не может быть больше или равна количеству вершин (n={n})."

    # Применяем алгоритм Гавела — Хакими для окончательной проверки
    # Сортируем последовательность по убыванию
    seq = sorted(degrees, reverse=True)
    
    while True:
        # Удаляем нули
        seq = [d for d in seq if d > 0]
        
        # Если последовательность пуста, граф существует
        if not seq:
            return True, "Граф существует."
        
        # Берем вершину с наибольшей степенью
        d = seq.pop(0)
        
        # Если наибольшая степень больше, чем количество оставшихся вершин
        if d > len(seq):
            return False, "Наибольшая степень превышает количество оставшихся вершин для соединения."
        
        # Вычитаем 1 из следующих d вершин
        for i in range(d):
            seq[i] -= 1
            # Если после вычитания получилось отрицательное число, граф невозможен
            if seq[i] < 0:
                return False, "Невозможно построить граф: не хватает вершин для соединения."
        
        # Снова сортируем
        seq.sort(reverse=True)

def main():
    print("Введите степенную последовательность через пробел.")
    print("Например: 3 3 2 2 2 2")
    
    while True:
        try:
            user_input = input("Степени вершин: ")
            degrees = list(map(int, user_input.split()))
            if len(degrees) == 0:
                print("Ошибка: последовательность не может быть пустой.")
                continue
            break
        except ValueError:
            print("Ошибка: вводите только целые числа, разделенные пробелами.")

    is_possible, message = check_graphical_sequence(degrees)

    print("\nРезультат:")
    if is_possible:
        print(f"Граф возможен. {message}")
    else:
        print(f"Граф невозможен. Причина: {message}")

if __name__ == "__main__":
    main()